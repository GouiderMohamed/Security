# RCON[0] non utilisé ; RCON[1..10] pour les 10 rounds
RCON = [0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36]

# ------------------------------------------------------------------ #
#  Multiplication dans GF(2^8) modulo 0x11B                          #
# ------------------------------------------------------------------ #

def gf_mul(a: int, b: int) -> int:
    """Multiplication dans GF(2^8) par la méthode des additions successives."""
    res = 0
    for _ in range(8):
        if b & 1:
            res ^= a
        hi = a & 0x80
        a = (a << 1) & 0xFF
        if hi:
            a ^= 0x1B
        b >>= 1
    return res

# ------------------------------------------------------------------ #
#  Expansion de clé (Key Schedule)                                    #
# ------------------------------------------------------------------ #

def aes_key_expansion(key: bytes) -> list[list[int]]:
    """
    Génère les 11 round-keys AES-128 à partir d'une clé de 16 octets.
    Retourne une liste de 11 listes de 16 entiers.
    """
    if len(key) != 16:
        raise ValueError(f"La clé AES-128 doit faire 16 octets (reçu {len(key)})")

    round_keys = [list(key)] + [[0] * 16 for _ in range(10)]

    for r in range(1, 11):
        prev = round_keys[r - 1]
        # RotWord + SubWord sur le dernier mot (octets 12-15, rotation 12→13)
        temp = [
            SBOX[prev[13]],
            SBOX[prev[14]],
            SBOX[prev[15]],
            SBOX[prev[12]],
        ]
        temp[0] ^= RCON[r]

        for i in range(4):
            round_keys[r][i]      = prev[i]      ^ temp[i]
            round_keys[r][4 + i]  = prev[4 + i]  ^ round_keys[r][i]
            round_keys[r][8 + i]  = prev[8 + i]  ^ round_keys[r][4 + i]
            round_keys[r][12 + i] = prev[12 + i] ^ round_keys[r][8 + i]

    return round_keys

# ------------------------------------------------------------------ #
#  Opérations internes sur l'état 4×4                                #
# ------------------------------------------------------------------ #

def _add_round_key(state: list[list[int]], rkey: list[int]) -> None:
    for c in range(4):
        for r in range(4):
            state[r][c] ^= rkey[c * 4 + r]


def _sub_bytes(state: list[list[int]], sbox: list[int]) -> None:
    for r in range(4):
        for c in range(4):
            state[r][c] = sbox[state[r][c]]


def _shift_rows(state: list[list[int]], inv: bool) -> None:
    """inv=False → décalage gauche (chiffrement), inv=True → droite (déchiffrement)."""
    for r in range(1, 4):
        row = state[r][:]
        shift = (4 - r) if inv else r
        for c in range(4):
            state[r][c] = row[(c + shift) % 4]


def _mix_columns(state: list[list[int]], inv: bool) -> None:
    """inv=False → MixColumns, inv=True → InvMixColumns."""
    for c in range(4):
        s0, s1, s2, s3 = state[0][c], state[1][c], state[2][c], state[3][c]
        if not inv:
            state[0][c] = gf_mul(2, s0) ^ gf_mul(3, s1) ^ s2            ^ s3
            state[1][c] = s0            ^ gf_mul(2, s1) ^ gf_mul(3, s2) ^ s3
            state[2][c] = s0            ^ s1            ^ gf_mul(2, s2) ^ gf_mul(3, s3)
            state[3][c] = gf_mul(3, s0) ^ s1            ^ s2            ^ gf_mul(2, s3)
        else:
            state[0][c] = gf_mul(0x0E, s0) ^ gf_mul(0x0B, s1) ^ gf_mul(0x0D, s2) ^ gf_mul(0x09, s3)
            state[1][c] = gf_mul(0x09, s0) ^ gf_mul(0x0E, s1) ^ gf_mul(0x0B, s2) ^ gf_mul(0x0D, s3)
            state[2][c] = gf_mul(0x0D, s0) ^ gf_mul(0x09, s1) ^ gf_mul(0x0E, s2) ^ gf_mul(0x0B, s3)
            state[3][c] = gf_mul(0x0B, s0) ^ gf_mul(0x0D, s1) ^ gf_mul(0x09, s2) ^ gf_mul(0x0E, s3)


def _bytes_to_state(data: bytes) -> list[list[int]]:
    state = [[0] * 4 for _ in range(4)]
    for i in range(16):
        state[i % 4][i // 4] = data[i]
    return state


def _state_to_bytes(state: list[list[int]]) -> bytes:
    return bytes(state[i % 4][i // 4] for i in range(16))

# ------------------------------------------------------------------ #
#  API publique                                                       #
# ------------------------------------------------------------------ #

def aes_encrypt(data_in: bytes, key: bytes) -> bytes:
    if len(data_in) != 16:
        raise ValueError(f"Le bloc AES doit faire 16 octets (reçu {len(data_in)})")

    rkeys = aes_key_expansion(key)
    state = _bytes_to_state(data_in)

    _add_round_key(state, rkeys[0])

    for r in range(1, 10):
        _sub_bytes(state, SBOX)
        _shift_rows(state, False)
        _mix_columns(state, False)
        _add_round_key(state, rkeys[r])

    # Dernier round : pas de MixColumns
    _sub_bytes(state, SBOX)
    _shift_rows(state, False)
    _add_round_key(state, rkeys[10])

    return _state_to_bytes(state)


def aes_decrypt(data_in: bytes, key: bytes) -> bytes:
    """
    Déchiffre un bloc de 16 octets avec AES-128.

    Args:
        data_in : ciphertext de 16 octets exactement.
        key     : clé de 16 octets exactement.

    Returns:
        Plaintext de 16 octets.
    """
    if len(data_in) != 16:
        raise ValueError(f"Le bloc AES doit faire 16 octets (reçu {len(data_in)})")

    rkeys = aes_key_expansion(key)
    state = _bytes_to_state(data_in)

    _add_round_key(state, rkeys[10])

    for r in range(9, 0, -1):
        _shift_rows(state, True)
        _sub_bytes(state, INV_SBOX)
        _add_round_key(state, rkeys[r])
        _mix_columns(state, True)

    # Dernier round inverse : pas de InvMixColumns
    _shift_rows(state, True)
    _sub_bytes(state, INV_SBOX)
    _add_round_key(state, rkeys[0])

    return _state_to_bytes(state)
